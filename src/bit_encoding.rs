//! Encode and decode DNA bases into bit representation.
//!
//! The main functions are those to encode and decode bases, and get their
//! reverse complement. Each bases uses two bits, and are packed into 64-bit
//! integers.
//!
//! Easy encoding from ASCII are the 3rd and 2nd bits (works with both
//! upper and lowercase)
//!
//! ```none
//! This encodes as A: 00; C: 01; T: 10; G: 11
//!
//! EOR w/ 10          10     10     10     10
//! gives rc           10     11     00     01
//! ```
//! [`valid_base`] accepts exactly A, C, G and T, in either case.

use bnum::BUint;
use num_traits::{PrimInt, Unsigned};

/// Table from bits 0-3 to ASCII (use [`decode_base()`] not this table).
const LETTER_CODE: [u8; 4] = *b"ACTG";

/// Encode an ASCII char to bits 0-3.
#[inline(always)]
pub fn encode_base(base: u8) -> u8 {
    (base >> 1) & 0x3
}

/// Decode bits 0-3 to ASCII.
#[inline(always)]
pub fn decode_base(bitbase: u8) -> u8 {
    LETTER_CODE[bitbase as usize]
}

/// Reverse complement an encoded base.
#[inline(always)]
pub fn rc_base(base: u8) -> u8 {
    base ^ 2
}

/// A, C, G or T, in either case, with ASCII input: anything else (N, other IUPAC codes, gaps) breaks a
/// k-mer. Lower-casing by OR-ing 0x20 maps exactly these eight bytes onto the four letters.
#[inline(always)]
pub fn valid_base(base: u8) -> bool {
    matches!(base | 0x20, b'a' | b'c' | b'g' | b't')
}

/// Trait to support both `u64`, `u128`, and larger integer format representation of split k-mers
pub trait UInt<'a>:
    PrimInt
    + Unsigned
    + std::fmt::Display
    + std::fmt::Debug
    + std::fmt::Binary
    + std::marker::Send
    + std::marker::Sync
    + std::hash::Hash
    + std::ops::Shl<usize, Output = Self>
    + std::ops::BitAnd
    + std::ops::ShrAssign<i32>
    + std::ops::ShlAssign<i32>
    + std::ops::BitOrAssign
    + std::borrow::BorrowMut<Self>
{
    /// Reverse complement of an encoded and packed split k-mer (64-bits).
    fn rev_comp(self, k_size: usize) -> Self;
    /// Convert to u8 as primitive
    fn as_u8(self) -> u8;
    /// Set to zero
    fn zero_init() -> Self;
    /// Convert from u8, encoded bases 0-3
    fn from_encoded_base(encoded_base: u8) -> Self;
    /// Number of bits in the representation
    fn n_bits(self) -> u32;
    /// Get one nucleotide already with an UTF-8 encoding
    fn get_one_nucleotide(self, i: usize) -> u8;
}

impl<'a> UInt<'a> for u64 {
    #[inline(always)]
    #[rustfmt::skip]
    fn rev_comp(mut self, k_size: usize) -> Self {
        // This part reverses the bases by shuffling them using an on/off pattern
        // of bits
        self = (self >> 2  & 0b00110011_00110011_00110011_00110011_00110011_00110011_00110011_00110011)
            |  (self       & 0b00110011_00110011_00110011_00110011_00110011_00110011_00110011_00110011) << 2;
        self = (self >> 4  & 0b00001111_00001111_00001111_00001111_00001111_00001111_00001111_00001111)
            |  (self       & 0b00001111_00001111_00001111_00001111_00001111_00001111_00001111_00001111) << 4;
        self = (self >> 8  & 0b00000000_11111111_00000000_11111111_00000000_11111111_00000000_11111111)
            |  (self       & 0b00000000_11111111_00000000_11111111_00000000_11111111_00000000_11111111) << 8;
        self = (self >> 16 & 0b00000000_00000000_11111111_11111111_00000000_00000000_11111111_11111111)
            |  (self       & 0b00000000_00000000_11111111_11111111_00000000_00000000_11111111_11111111) << 16;
        self = (self >> 32 & 0b00000000_00000000_00000000_00000000_11111111_11111111_11111111_11111111)
            |  (self       & 0b00000000_00000000_00000000_00000000_11111111_11111111_11111111_11111111) << 32;
        // This reverse complements
        self ^= 0b10101010_10101010_10101010_10101010_10101010_10101010_10101010_10101010;

        // Shifts so LSB is at the bottom
        self >> (2 * (32 - k_size))
    }

    #[inline(always)]
    fn as_u8(self) -> u8 {
        self as u8
    }

    #[inline(always)]
    fn zero_init() -> Self {
        0
    }

    #[inline(always)]
    fn from_encoded_base(encoded_base: u8) -> Self {
        encoded_base as Self
    }

    #[inline(always)]
    fn n_bits(self) -> u32 {
        Self::BITS
    }

    #[inline(always)]
    fn get_one_nucleotide(self, i: usize) -> u8 {
        decode_base(((self >> (i * 2)) & 0x3) as u8)
    }
}

